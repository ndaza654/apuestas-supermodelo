def pmf(k,l): return exp(-l)*l**k/factorial(k)
def ge(k,l): return 1-sum(pmf(i,l) for i in range(k)) if k>0 else 1.0
def le(k,l): return sum(pmf(i,l) for i in range(k+1))
def rng(k,a,b,l): return sum(pmf(i,l) for i in range(a,b+1))
